import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
let stage=3,visible=true,nextId=0;
const tasks=new Map(),states=[],visited=[],beats=[];
const context=vm.createContext({setTimeout,clearTimeout});
vm.runInContext(readFileSync(new URL('refinement-playback.js',import.meta.url),'utf8')+';this.create=createRefinementPlayback;',context);
const player=context.create({getStage:()=>stage,setStage:n=>{stage=n;visited.push(n)},canPlay:()=>visible,onPlaying:(on,phase)=>states.push(phase),onBeat:n=>beats.push(n),schedule:(fn,delay)=>{const id=++nextId;tasks.set(id,{fn,delay});return id},unschedule:id=>tasks.delete(id)});
const next=()=>{const [id,task]=tasks.entries().next().value;tasks.delete(id);assert.equal(task.delay,stage===1?1200:1800);task.fn()};
// A new walkthrough has an explicit beginning even from a shared later stage.
player.start();assert.equal(stage,1);assert.equal(player.running,true);assert.equal(tasks.size,1);
next();assert.equal(stage,2);next();assert.equal(stage,3);next();assert.equal(stage,4);
assert.equal(player.running,true);next();assert.equal(player.phase,'complete');assert.equal(tasks.size,0);
assert.deepEqual(visited,[1,2,3,4]);assert.deepEqual(beats,[1,2,3,4]);assert.equal(stage,4);
player.toggle();assert.equal(stage,1);next();player.toggle();assert.equal(player.phase,'paused');assert.equal(stage,2);assert.equal(tasks.size,0);
player.toggle();assert.equal(stage,2);next();assert.equal(stage,3);
visible=false;next();assert.equal(stage,3);assert.equal(player.phase,'paused');assert.equal(tasks.size,0);
player.start();assert.equal(player.running,false);visible=true;player.start();const stale=tasks.values().next().value.fn;
player.stop();player.start();stale();assert.equal(stage,1);assert.equal(tasks.size,1);
next();assert.equal(stage,2);player.stop();assert.equal(player.phase,'idle');assert.equal(tasks.size,0);
player.toggle();assert.equal(stage,1);player.pause();assert.equal(player.phase,'paused');assert.equal(tasks.size,0);
console.log('PASS: 4.8s to the final saved result, four explanatory beats, explicit restart, held finale, pause/resume, cancellation, stale timer and visibility guards.');
